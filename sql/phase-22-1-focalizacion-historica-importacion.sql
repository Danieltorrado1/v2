INSERT INTO modalidad_aliases (modalidad_id, alias, alias_normalizado)
SELECT DISTINCT ON (m.id, upper(regexp_replace(unaccent(alias.alias), '[^A-Za-z0-9]+', ' ', 'g')))
  m.id,
  alias.alias,
  upper(regexp_replace(unaccent(alias.alias), '[^A-Za-z0-9]+', ' ', 'g'))
FROM modalidades m
JOIN (
  VALUES
    ('CAA-JU', 'CAA JU'),
    ('CAA-JU', 'CAA - JU'),
    ('CAJU-RI', 'CAJU RI'),
    ('CAJU-RI', 'CAJU - RI'),
    ('CAJM/JT-RI', 'CAJM JT RI'),
    ('CAJM/JT-RI', 'CAJM/JT RI')
) AS alias(codigo_original, alias)
  ON m.codigo_original = alias.codigo_original
ORDER BY m.id, upper(regexp_replace(unaccent(alias.alias), '[^A-Za-z0-9]+', ' ', 'g')), alias.alias
ON CONFLICT DO NOTHING;