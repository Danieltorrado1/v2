    estado,
    observacion_cambio,
    usuario_creacion,
    usuario_modificacion,
    creado_en,
    modificado_en
  )
  SELECT
    1,
    'Cobertura PAE ' || cc.numero_contrato || ' - ' || m.codigo_original,
    'Regla base de cobertura PAE migrada en phase-22-1',
    'rangos',
    m.codigo_original,
    m.id,
    cc.contrato_id,
    'COBERTURA_PAE',
    CASE WHEN m.codigo_original = 'CAARES' THEN 4 ELSE NULL END,
    NULL,
    ARRAY['cupos','total','cupos_calculo','contrato_id']::text[],
    0,
    NULL,
    'ceil',
    NULL,
    cc.vigencia_desde,
    cc.vigencia_hasta,
    'activo',
    'Semilla inicial de reglas de cobertura PAE',
    (SELECT id FROM usuarios ORDER BY id ASC LIMIT 1),
    (SELECT id FROM usuarios ORDER BY id ASC LIMIT 1),
    NOW(),
    NOW()
  FROM contratos_cobertura cc
  CROSS JOIN modalidades m
  WHERE m.codigo_original IN ('CAA', 'CAA-JU', 'CAARES', 'CAJM/JT-RI', 'CAJU-RI')
    AND NOT EXISTS (
      SELECT 1
      FROM calculadora_personal_config existing
      WHERE COALESCE(existing.dominio_calculo, 'GENERAL') = 'COBERTURA_PAE'
        AND existing.contrato_id = cc.contrato_id
        AND existing.modalidad_id = m.id
        AND existing.estado = 'activo'
    )
  RETURNING id, contrato_id, modalidad_id, modalidad
)
