WITH contratos_cobertura AS (
  SELECT
    c.id AS contrato_id,
    c.numero_contrato,
    COALESCE(c.fecha_inicio::date, CURRENT_DATE) AS vigencia_desde,
    COALESCE(c.fecha_final_real::date, c.fecha_final_estimada::date) AS vigencia_hasta
  FROM contratos c
  WHERE COALESCE(c.aplica_cobertura, FALSE) = TRUE
),
seed_configs AS (
  INSERT INTO calculadora_personal_config (
    version,
    nombre,
