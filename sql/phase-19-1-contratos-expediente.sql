CREATE TABLE IF NOT EXISTS documentos_contrato (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  contrato_id BIGINT NOT NULL REFERENCES contratos(id),
  requisito_id BIGINT NULL REFERENCES contrato_documento_requisitos(id),
  tipo_documento_id BIGINT NOT NULL REFERENCES tipos_documentos(id),
  categoria TEXT NOT NULL DEFAULT 'EJECUCION',
  archivo_path TEXT NULL,
  storage_bucket TEXT NOT NULL,
  storage_path TEXT NOT NULL,
  nombre_original TEXT NOT NULL,
  mime_type TEXT NOT NULL,
  tamano_bytes BIGINT NOT NULL,
  fecha_expedicion DATE NULL,
  fecha_vencimiento DATE NULL,
  fecha_carga TIMESTAMP NOT NULL DEFAULT NOW(),
  vigencia_dias_configurada INTEGER NULL,
  version INTEGER NOT NULL DEFAULT 1,
  documento_reemplaza_id BIGINT NULL REFERENCES documentos_contrato(id),
  es_vigente BOOLEAN NOT NULL DEFAULT TRUE,
  estado_revision TEXT NOT NULL DEFAULT 'PENDIENTE',
  motivo_devolucion TEXT NULL,
  revisado_por_usuario_id BIGINT NULL REFERENCES usuarios(id),
  revisado_at TIMESTAMP NULL,
  observaciones TEXT NULL,
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMP NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMP NOT NULL DEFAULT NOW(),
  CONSTRAINT chk_documentos_contrato_categoria CHECK (
    categoria IN (
      'CREACION_EMPRESA_JURIDICA',
      'INICIO_CONTRATO',
      'EJECUCION',
      'CIERRE'
    )
  ),
  CONSTRAINT chk_documentos_contrato_estado_revision CHECK (
    estado_revision IN ('PENDIENTE', 'EN_REVISION', 'APROBADO', 'DEVUELTO', 'ANULADO')
  )
);

CREATE INDEX IF NOT EXISTS idx_documentos_contrato_contrato
  ON documentos_contrato (contrato_id, categoria, fecha_carga DESC);

CREATE INDEX IF NOT EXISTS idx_documentos_contrato_tipo
  ON documentos_contrato (tipo_documento_id, contrato_id);

CREATE UNIQUE INDEX IF NOT EXISTS uq_documentos_contrato_requisito_vigente
  ON documentos_contrato (contrato_id, requisito_id)
  WHERE requisito_id IS NOT NULL AND es_vigente = TRUE AND activo = TRUE;

CREATE UNIQUE INDEX IF NOT EXISTS uq_documentos_contrato_tipo_vigente_sin_requisito
  ON documentos_contrato (contrato_id, tipo_documento_id)
  WHERE requisito_id IS NULL AND es_vigente = TRUE AND activo = TRUE;

