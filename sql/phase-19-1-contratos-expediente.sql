CREATE TABLE IF NOT EXISTS contrato_eventos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  contrato_id BIGINT NOT NULL REFERENCES contratos(id),
  tipo_evento TEXT NOT NULL,
  fecha_evento DATE NOT NULL,
  fecha_efecto_desde DATE NULL,
  fecha_efecto_hasta DATE NULL,
  descripcion TEXT NULL,
  motivo TEXT NULL,
  documento_soporte_id BIGINT NULL,
  usuario_creador_id BIGINT NULL REFERENCES usuarios(id),
  datos_anteriores JSONB NULL,
  datos_posteriores JSONB NULL,
  estado_evento TEXT NOT NULL DEFAULT 'ACTIVO',
  motivo_anulacion TEXT NULL,
  anulado_por_usuario_id BIGINT NULL REFERENCES usuarios(id),
  anulado_at TIMESTAMP NULL,
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMP NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMP NOT NULL DEFAULT NOW(),
  CONSTRAINT chk_contrato_eventos_tipo CHECK (
    tipo_evento IN (
      'CREACION',
      'ACTA_INICIO',
      'PRORROGA',
      'ADICION',
      'OTROSI',
      'MODIFICACION',
      'SUSPENSION',
      'REINICIO',
      'TERMINACION',
      'LIQUIDACION',
      'CAMBIO_REPRESENTANTE',
      'CAMBIO_SUPERVISOR',
      'CAMBIO_COBERTURA',
      'OTRO'
    )
  ),
  CONSTRAINT chk_contrato_eventos_estado CHECK (
    estado_evento IN ('ACTIVO', 'ANULADO')
  )
);

CREATE INDEX IF NOT EXISTS idx_contrato_eventos_contrato_fecha
  ON contrato_eventos (contrato_id, fecha_evento DESC, id DESC);

