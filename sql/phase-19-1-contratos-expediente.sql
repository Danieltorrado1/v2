UPDATE contratos
SET estado_contractual = CASE
  WHEN COALESCE(activo, TRUE) = FALSE THEN 'BORRADOR'
  WHEN fecha_inicio > CURRENT_DATE THEN 'PENDIENTE_INICIO'
  ELSE 'ACTIVO'
END
WHERE estado_contractual IS NULL;

