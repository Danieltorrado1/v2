  nombre_requisito TEXT NOT NULL,
  descripcion TEXT NULL,
  obligatorio BOOLEAN NOT NULL DEFAULT TRUE,
  criticidad TEXT NOT NULL DEFAULT 'MEDIA',
  bloquea_creacion BOOLEAN NOT NULL DEFAULT FALSE,
  bloquea_inicio BOOLEAN NOT NULL DEFAULT FALSE,
  bloquea_ejecucion BOOLEAN NOT NULL DEFAULT FALSE,
  bloquea_cierre BOOLEAN NOT NULL DEFAULT FALSE,
  solo_alerta BOOLEAN NOT NULL DEFAULT FALSE,
  responsable TEXT NULL,
  plazo_regularizacion_dias INTEGER NULL,
  orden INTEGER NOT NULL DEFAULT 0,
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMP NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMP NOT NULL DEFAULT NOW(),
  CONSTRAINT chk_contrato_documento_requisitos_categoria CHECK (
    categoria IN (
      'CREACION_EMPRESA_JURIDICA',
      'INICIO_CONTRATO',
      'EJECUCION',
      'CIERRE'
    )
  ),
